FISH = """\
# fish completion for {app} — generated by `lfs completions fish`
complete -c lfs -f

# subcommands
{fish_subcommands}

# flags
{fish_flags}

# paths complete for the first positional argument
complete -c lfs -n '__fish_is_nth_token 1' -a '(__fish_complete_path)'
complete -c lfs -n '__fish_is_nth_token 1' -xa '(__fish_complete_directories)'

# don't offer files after a subcommand is given
complete -c lfs -n 'not __fish_seen_subcommand_from {sub_names}' -a '(__fish_complete_path)'
"""

BASH = """\
# bash completion for {app} — generated by `lfs completions bash`
_{func}() {{
    local cur prev words cword
    _init_completion || {{
        cur="${{COMP_WORDS[COMP_CWORD]}}"
        prev="${{COMP_WORDS[COMP_CWORD-1]}}"
        words=("${{COMP_WORDS[@]}}")
        cword=$COMP_CWORD
    }}

    local subcommands="{sub_names}"
    local flags="{flag_list}"

    case "$prev" in
        --mode|-m)  COMPREPLY=( $(compgen -W "download serve stream torrent" -- "$cur") ); return 0 ;;
        --theme)    COMPREPLY=( $(compgen -W "dark light mono" -- "$cur") ); return 0 ;;
        --port|-p)  COMPREPLY=(); return 0 ;;
        config)     COMPREPLY=( $(compgen -W "show init get set edit path reset" -- "$cur") ); return 0 ;;
        completions|completion) COMPREPLY=( $(compgen -W "fish bash powershell zsh" -- "$cur") ); return 0 ;;
        theme)      COMPREPLY=( $(compgen -W "dark light mono list" -- "$cur") ); return 0 ;;
    esac

    if [[ "$cur" == -* ]]; then
        COMPREPLY=( $(compgen -W "$flags" -- "$cur") )
        return 0
    fi

    if [[ $cword -eq 1 ]]; then
        COMPREPLY=( $(compgen -W "$subcommands" -- "$cur") $(compgen -f -- "$cur") )
        return 0
    fi

    if [[ "$subcommands" != *"${{words[1]}}"* ]]; then
        COMPREPLY=( $(compgen -f -- "$cur") )
    fi
}}
complete -o filenames -F _{func} lfs
complete -o filenames -F _{func} local-file-sharer
"""

POWERSHELL = """\
# PowerShell completion for {app} — generated by `lfs completions powershell`
# Save as local-file-sharer-completions.ps1 and dot-source it from $PROFILE,
# or let install.ps1 do it for you.

$script:LfsSubcommands = @({ps_subcommands})
$script:LfsFlags = @({ps_flags})
$script:LfsThemeValues = @('dark', 'light', 'mono')
$script:LfsModes = @('download', 'serve', 'stream', 'torrent')

Register-ArgumentCompleter -Native -CommandName @('lfs', 'local-file-sharer') -ScriptBlock {{
    param($wordToComplete, $commandAst, $cursorPosition)

    $tokens = $commandAst.CommandElements | ForEach-Object {{ $_.ToString() }}
    $previous = if ($tokens.Count -ge 2) {{ $tokens[-1] }} else {{ '' }}
    if ($wordToComplete -and $previous -eq $wordToComplete) {{ $previous = $tokens[-2] }}

    $suggestions = switch ($previous) {{
        '--mode' {{ $LfsModes }}
        '-m'     {{ $LfsModes }}
        '--theme' {{ $LfsThemeValues }}
        'theme'  {{ $LfsThemeValues + 'list' }}
        'config' {{ @('show','init','get','set','edit','path','reset') }}
        'completions' {{ @('fish','bash','powershell','zsh') }}
        default {{ @() }}
    }}

    if (-not $suggestions) {{
        if ($wordToComplete -like '-*') {{ $suggestions = $LfsFlags }}
        elseif ($tokens.Count -le 1) {{ $suggestions = $LfsSubcommands }}
    }}

    $suggestions | Where-Object {{ $_ -like "$wordToComplete*" }} | ForEach-Object {{
        [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)
    }}

    # Fall back to filesystem completion for paths
    if ($wordToComplete -notlike '-*') {{
        Get-ChildItem -Name -Path "$wordToComplete*" -ErrorAction SilentlyContinue |
            ForEach-Object {{ [System.Management.Automation.CompletionResult]::new($_, $_, 'ProviderItem', $_) }}
    }}
}}
"""


def _fish_quote(text: str) -> str:
    return text.replace("\\", "\\\\").replace("'", "\\'")


def fish_script(app: str = "lfs") -> str:
    subcommands = "\n".join(
        f"complete -c {{app}} -n '__fish_use_subcommand' -f -a {name} -d '{_fish_quote(desc)}'"
        for name, desc in SUBCOMMANDS.items()
    )
    lines = []
    for short, long, desc in FLAGS:
        if short:
            lines.append(
                f"complete -c {{app}} -s {short.lstrip('-')} -l {long.lstrip('-')} -d '{_fish_quote(desc)}'"
            )
        else:
            lines.append(f"complete -c {{app}} -l {long.lstrip('-')} -d '{_fish_quote(desc)}'")
    flags = "\n".join(lines)
    return FISH.format(
        app=app,
        fish_subcommands=subcommands.format(app=app),
        fish_flags=flags.format(app=app),
        sub_names=" ".join(SUBCOMMANDS),
    )


def bash_script(app: str = "lfs") -> str:
    func = app.replace("-", "_")
    flag_list = " ".join(
        sorted({f"{short}" for short, _l, _d in FLAGS if short} | {long for _s, long, _d in FLAGS})
    )
    return BASH.format(
        app=APP_NAME,
        func=func,
        sub_names=" ".join(SUBCOMMANDS),
        flag_list=flag_list,
    )


def powershell_script(app: str = "lfs") -> str:
    ps_sub = ", ".join(f"'{name}'" for name in SUBCOMMANDS)
    ps_flags = ", ".join(f"'{long}'" for _s, long, _d in FLAGS)
    return POWERSHELL.format(app=APP_NAME, ps_subcommands=ps_sub, ps_flags=ps_flags)


def zsh_script(app: str = "lfs") -> str:
    args = " ".join(f"'{name}:{desc}'" for name, desc in SUBCOMMANDS.items())
    return f"""\
#compdef {app}
# zsh completion for {APP_NAME} — generated by `lfs completions zsh`
_{app.replace("-", "_")}() {{
  _arguments '1: :->cmd' '*: :->args'
  case $state in
    cmd) _values 'command' {args} ;;
    args) _files ;;
  esac
}}
_{app.replace("-", "_")} "$@"
"""


SCRIPTS = {
    "fish": fish_script,
    "bash": bash_script,
    "powershell": powershell_script,
    "pwsh": powershell_script,
    "zsh": zsh_script,
}


def get_script(shell: str) -> str:
    shell = shell.strip().lower()
    if shell not in SCRIPTS:
        raise ValueError(f"unsupported shell {shell!r} (choose from {', '.join(SCRIPTS)})")
    return SCRIPTS[shell]()


def install_path(shell: str) -> str:
    shell = shell.lower()
    if shell == "fish":
        return "~/.config/fish/completions/lfs.fish"
    if shell == "bash":
        return "~/.local/share/bash-completion/completions/lfs  (or /etc/bash_completion.d/lfs)"
    if shell in ("powershell", "pwsh"):
        return "add to $PROFILE: `local-file-sharer completions powershell | Out-String | Invoke-Expression`"
    if shell == "zsh":
        return "~/.zfunc/_lfs"
    return "unknown shell"


